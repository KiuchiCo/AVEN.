import { createHash } from 'node:crypto';
import { createReadStream, createWriteStream } from 'node:fs';
import { mkdir, rename, rm, stat } from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';
import { Transform, type Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { PayloadTooLargeException } from '@nestjs/common';
import { formatBytes } from './file-rules.js';

/**
 * Where file contents live. PostgreSQL only ever holds metadata.
 * Drivers: local disk and S3-compatible object storage (see s3-storage.ts).
 */
export interface StorageDriver {
  /** Streams `source` to `key`. Rejects with 413 (leaving nothing behind) if it exceeds `maxBytes`. */
  put(key: string, source: Readable, maxBytes: number): Promise<{ size: number; checksum: string }>;
  get(key: string): Promise<{ stream: Readable; size: number }>;
  delete(key: string): Promise<void>;
}

export class LocalStorageDriver implements StorageDriver {
  private readonly root: string;

  constructor(directory: string) {
    this.root = resolve(directory);
  }

  /** Keys are generated by the API, but this still refuses anything that would escape the storage directory. */
  private pathFor(key: string) {
    const path = resolve(this.root, key);
    if (!path.startsWith(this.root + sep) || /[\0]/.test(key)) throw new Error('Invalid storage key.');
    return path;
  }

  async put(key: string, source: Readable, maxBytes: number) {
    const path = this.pathFor(key);
    const partial = `${path}.part`;
    await mkdir(dirname(path), { recursive: true });
    const hash = createHash('sha256');
    let size = 0;
    const meter = new Transform({
      transform(chunk: Buffer, _encoding, callback) {
        size += chunk.length;
        if (size > maxBytes) return callback(new PayloadTooLargeException(`Files can be up to ${formatBytes(maxBytes)}.`));
        hash.update(chunk);
        callback(null, chunk);
      },
    });
    try {
      await pipeline(source, meter, createWriteStream(partial, { flags: 'wx', mode: 0o600 }));
      await rename(partial, path);
    } catch (error) {
      await rm(partial, { force: true });
      throw error;
    }
    return { size, checksum: hash.digest('hex') };
  }

  async get(key: string) {
    const path = this.pathFor(key);
    const { size } = await stat(path);
    return { stream: createReadStream(path), size };
  }

  async delete(key: string) {
    await rm(this.pathFor(key), { force: true });
  }
}
